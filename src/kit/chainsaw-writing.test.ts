import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { WRITING_CAP } from "../scenes/sign-platform";
import { checkLayouts } from "./legibility";
import { CHAINSAW_FACE, CHAINSAW_X, marqueeLayout } from "./marquee";
import { CHAINSAW_WRITING } from "./chainsaw-writing";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const read = (rel: string) => readFileSync(`${ROOT}${rel}`, "utf8");
const git = (...args: string[]) => execFileSync("git", args, { cwd: ROOT });
/** The branch the word was composed on (#441): absent in a shallow clone, so the byte-for-byte check skips there. */
const OLD = "origin/feature/writing-tabla-flotante:src/kit/chainsaw-writing.ts";
const hasOld = (() => { try { git("cat-file", "-e", OLD); return true; } catch { return false; } })();

describe("WRITING in Chainsaw Carnage (#442)", () => {
  it("the word is WRITING, seven letters", () => {
    expect(CHAINSAW_WRITING.text).toBe("WRITING");
    expect(CHAINSAW_WRITING.letters.map((l) => l.char).join("")).toBe("WRITING");
  });
  it("passes level 1 at WRITING_CAP with the Chainsaw face as stroke", () => {
    expect(checkLayouts(marqueeLayout(WRITING_CAP, 0, CHAINSAW_WRITING), WRITING_CAP, CHAINSAW_FACE * WRITING_CAP)).toEqual([]);
  });
  it("CHAINSAW_X is the ink height of the shortest letter, within a hundredth of a cap", () => {
    expect(Math.min(...marqueeLayout(1, 0, CHAINSAW_WRITING).map((g) => g.box.y1 - g.box.y0))).toBeCloseTo(CHAINSAW_X, 2);
  });
  it("the word holds 382 triangles", () => {
    expect(marqueeLayout(1, 0, CHAINSAW_WRITING).reduce((n, g) => n + g.quads.length, 0)).toBe(382);
  });
  it("the generated file credits Chainsaw Carnage and its license", () => {
    expect(read("src/kit/chainsaw-writing.ts").split("\n")[0]).toBe("// Generated by scripts/marquee-word.py from Chainsaw Carnage (GGBotNet, SIL Open Font License).");
  });
  it.skipIf(!hasOld)("the word file is byte for byte the one of the floating-board branch", () => {
    expect(readFileSync(`${ROOT}src/kit/chainsaw-writing.ts`).equals(git("show", OLD))).toBe(true);
  });
  it("marquee-word.py documents the Writing command, the font's page and download, and takes close, speck and tol", () => {
    const doc = read("scripts/marquee-word.py");
    for (const s of [
      "https://www.1001fonts.com/chainsaw-carnage-font.html", "https://www.1001fonts.com/download/chainsaw-carnage.zip",
      "0 0.13 0 0.005 0.004 > src/kit/chainsaw-writing.ts", 'close="0", speck="0", tol="0"', "sys.argv[1:10]",
    ]) expect(doc, s).toContain(s);
    expect(doc).not.toMatch(/LostWages/);
  });
  it("the previous Writing fonts are gone: no word files, no constants (#437, #442)", () => {
    expect(existsSync(`${ROOT}src/kit/lostwages-writing.ts`)).toBe(false);
    expect(existsSync(`${ROOT}src/kit/chancery-writing.ts`)).toBe(false);
    expect(read("src/kit/marquee.ts")).not.toMatch(/LOSTWAGES|CHANCERY/);
  });
  it("no code file under src/ or scripts/, nor CONTEXT.md, names a previous Writing font", () => {
    const files = git("ls-files", "src", "scripts", "CONTEXT.md").toString().split("\n").filter((f) => f && !f.endsWith(".test.ts") && existsSync(`${ROOT}${f}`));
    expect(files.length).toBeGreaterThan(0);
    for (const f of files) expect(read(f), f).not.toMatch(/LostWages|LOSTWAGES|Black Chancery|CHANCERY/);
  });
  it("no font file is tracked", () => {
    expect(git("ls-files").toString().split("\n").filter((f) => /\.(ttf|otf|woff2?)$/i.test(f))).toEqual([]);
  });
});
