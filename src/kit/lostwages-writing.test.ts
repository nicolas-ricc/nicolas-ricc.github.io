import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { WRITING_CAP } from "../scenes/sign-platform";
import { checkLayouts } from "./legibility";
import { LOSTWAGES_FACE, marqueeLayout } from "./marquee";
import { LOSTWAGES_WRITING } from "./lostwages-writing";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const read = (rel: string) => readFileSync(`${ROOT}${rel}`, "utf8");

describe("WRITING in LostWages (#437)", () => {
  it("the word is WRITING, seven filled capitals without bulbs or loose parts", () => {
    expect(LOSTWAGES_WRITING.text).toBe("WRITING");
    expect(LOSTWAGES_WRITING.letters.map((l) => l.char).join("")).toBe("WRITING");
    expect(LOSTWAGES_WRITING.bulbRadius).toBe(0);
    for (const l of LOSTWAGES_WRITING.letters) {
      expect(l.parts, l.char).toBeUndefined();
      expect(l.bulbs, l.char).toEqual([]);
    }
  });
  it("passes level 1 at WRITING_CAP with the LostWages face as stroke", () => {
    expect(checkLayouts(marqueeLayout(WRITING_CAP, 0, LOSTWAGES_WRITING), WRITING_CAP, LOSTWAGES_FACE * WRITING_CAP)).toEqual([]);
  });
  it("the generated file credits LostWages and its license", () => {
    expect(read("src/kit/lostwages-writing.ts").split("\n")[0]).toBe("// Generated by scripts/marquee-word.py from LostWages (Nick Curtis, 1001Fonts Free For Commercial Use).");
  });
  it("Black Chancery is gone: no word file, no constants", () => {
    expect(existsSync(`${ROOT}src/kit/chancery-writing.ts`)).toBe(false);
    expect(read("src/kit/marquee.ts")).not.toMatch(/CHANCERY/);
  });
  it("marquee-word.py documents how to regenerate the word, with the font's URL and the closing", () => {
    const doc = read("scripts/marquee-word.py");
    for (const s of [
      "https://www.1001fonts.com/lostwages-font.html", "https://www.1001fonts.com/download/lostwages.zip",
      "WRITING LOSTWAGES_WRITING", "-0.0133 0.145 0.015 > src/kit/lostwages-writing.ts",
    ]) expect(doc, s).toContain(s);
    expect(doc).not.toMatch(/Chancery/);
  });
  it("no font file is committed", () => {
    const files = execFileSync("git", ["ls-files"], { cwd: ROOT, encoding: "utf8" }).split("\n");
    expect(files.filter((f) => /\.(ttf|otf|woff2?)$/i.test(f))).toEqual([]);
  });
});
