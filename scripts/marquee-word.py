"""Turns a word set in Neon Light (Font Bundles) into the geometry of `src/kit/marquee-resume.ts`.

The font's license forbids distributing it or converting it to other formats,
so the TTF is not in the repo: download it from
https://www.1001fonts.com/neon-light-font.html and pass its path. What is
committed is only the composed word, as artwork.

    python3 -P scripts/marquee-word.py ~/Downloads/NeonLight-Regular.ttf RESUME > src/kit/marquee-resume.ts

Needs fontTools (`pip install fonttools`).
"""
import math
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

STEPS = 4  # segments per quadratic curve


class Flatten(BasePen):
    def __init__(self, glyphs):
        super().__init__(glyphs)
        self.contours = []

    def _moveTo(self, p):
        self.contours.append([p])

    def _lineTo(self, p):
        self.contours[-1].append(p)

    def _qCurveToOne(self, a, b):
        p0 = self.contours[-1][-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            self.contours[-1].append(tuple((1 - t) ** 2 * p0[k] + 2 * (1 - t) * t * a[k] + t * t * b[k] for k in (0, 1)))

    def _curveToOne(self, a, b, c):
        p0 = self.contours[-1][-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.contours[-1].append(tuple(u**3 * p0[k] + 3 * u * u * t * a[k] + 3 * u * t * t * b[k] + t**3 * c[k] for k in (0, 1)))


def area(c):
    return sum(c[i][0] * c[i - 1][1] - c[i - 1][0] * c[i][1] for i in range(len(c))) / 2


def main(path, word):
    font = TTFont(path)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    cap = font["OS/2"].sCapHeight
    n = lambda v: round(v / cap, 4)
    pts = lambda c: ", ".join(f"{n(x)}, {n(y)}" for x, y in (c[:-1] if c[0] == c[-1] else c))
    out, dx, radius = [], 0, None
    for ch in word:
        g = glyphs[cmap[ord(ch)]]
        pen = Flatten(glyphs)
        g.draw(pen)
        body, counters, bulbs = None, [], []
        for c in pen.contours:
            a = area(c)
            xs, ys = [p[0] for p in c], [p[1] for p in c]
            w, h = max(xs) - min(xs), max(ys) - min(ys)
            if a > 0:
                if body is not None:
                    raise SystemExit(f"{ch}: more than one outer contour")
                body = c
            elif max(w, h) < 0.06 * cap and abs(abs(a) / (math.pi * w * h / 4) - 1) < 0.1:
                bulbs.append(((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2))
                radius = (w + h) / 4 if radius is None else radius
            else:
                counters.append(c)
        shift = lambda c: [(x + dx, y) for x, y in c]
        out.append((ch, shift(body), [shift(c) for c in counters], [(x + dx, y) for x, y in bulbs]))
        dx += g.width
    lines = [
        "// Generated by scripts/marquee-word.py from Neon Light (Font Bundles, free for commercial use;",
        "// Premium License). Only the composed word is committed, never the font. Do not edit by hand.",
        'import type { Vec2 } from "../iso/geometry";',
        "",
        "const poly = (...c: number[]): Vec2[] => { const o: Vec2[] = []; for (let i = 0; i < c.length; i += 2) o.push({ x: c[i]!, y: c[i + 1]! }); return o; };",
        "",
        "/** A marquee letter: filled `outline`, `counters` cut out of it and the bulbs along its stroke, in cap-height units (cap 1, baseline 0). */",
        "export interface MarqueeLetter { char: string; outline: Vec2[]; counters: Vec2[][]; bulbs: Vec2[] }",
        "",
        f"/** The word {word} in Neon Light, laid out with the font's advances: `width` and `bulbRadius` in cap-height units. */",
        f"export const MARQUEE_{word} = {{",
        f"  text: {word!r},".replace("'", '"'),
        f"  width: {n(dx)},",
        f"  bulbRadius: {n(radius)},",
        "  letters: [",
    ]
    for ch, body, counters, bulbs in out:
        lines.append(f'    {{ char: "{ch}", outline: poly({pts(body)}),')
        lines.append(f"      counters: [{', '.join(f'poly({pts(c)})' for c in counters)}],")
        lines.append(f"      bulbs: poly({', '.join(f'{n(x)}, {n(y)}' for x, y in bulbs)}) }},")
    lines += ["  ] as MarqueeLetter[],", "} as const;", ""]
    sys.stdout.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "RESUME")
